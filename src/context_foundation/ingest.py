def shown_path(rel: str) -> str:
    """表示と meta に使うパス。UTF-8 にできない名前(Linux での Shift_JIS の名前など)は、そのバイトを \\x.. で書く。"""
    try:
        rel.encode("utf-8")
        return rel
    except UnicodeEncodeError:
        return os.fsencode(rel).decode("utf-8", "backslashreplace")


def _count(counts: dict[str, int], examples: dict[str, list[str]], reason: str, rel: str) -> None:
    counts[reason] = counts.get(reason, 0) + 1
    ex = examples.setdefault(reason, [])
    if len(ex) < 5:
        ex.append(shown_path(rel))


@dataclass
class IngestStats:
    scanned: int = 0                 # 見たファイルの数(除外したフォルダの中は数えない)
    included: int = 0
    skipped: dict[str, int] = field(default_factory=dict)
    examples: dict[str, list[str]] = field(default_factory=dict)   # 理由ごとに、除いたファイルの例を少し
    # 入らなかったフォルダ(link_dir: フォルダのリンクやジャンクション、unreadable_dir: 中を一覧できなかった)
    skipped_dirs: dict[str, int] = field(default_factory=dict)
    dir_examples: dict[str, list[str]] = field(default_factory=dict)
    # 既定の名前で除いたフォルダと、その中の、索引に入りうるファイルの数([source:パス, 数])
    excluded_dirs: list[list] = field(default_factory=list)
    nested_roots: list[str] = field(default_factory=list)   # ほかの source のルートなので、こちらでは歩かなかったフォルダ
    chunk_failed: int = 0            # 分割の途中で落ちて、行で分け直したファイル
    chunk_failed_examples: list[str] = field(default_factory=list)

    def skip(self, reason: str, rel: str) -> None:
        _count(self.skipped, self.examples, reason, rel)

    def skip_dir(self, reason: str, rel: str) -> None:
        _count(self.skipped_dirs, self.dir_examples, reason, rel)

    def chunk_failure(self, where: str) -> None:
        self.chunk_failed += 1
        if len(self.chunk_failed_examples) < 5:
            self.chunk_failed_examples.append(shown_path(where))

    def extra_meta(self) -> dict:
        """索引の meta の stats に足す項目(0.4.0 から。あるものだけを書く。無ければ何も足さない)。"""
        out: dict = {}
        if self.skipped_dirs:
            out["skipped_dirs"] = dict(self.skipped_dirs)
            out["skipped_dir_examples"] = self.dir_examples
        dirs = sorted((d for d in self.excluded_dirs if d[1]), key=lambda d: (-d[1], d[0]))
        if dirs:
            out["excluded_dirs"] = {"folders": len(dirs), "files": sum(d[1] for d in dirs),
                                    "examples": [{"path": p, "files": n} for p, n in dirs[:20]]}
        if self.nested_roots:
            out["nested_roots"] = self.nested_roots[:20]
        if self.chunk_failed:
            out["chunk_failed"] = {"count": self.chunk_failed, "examples": self.chunk_failed_examples}
        return out


def language_of(name: str) -> str | None:
    lower = name.lower()
    ext = os.path.splitext(lower)[1]
    if ext in LANG_BY_EXT:
        return LANG_BY_EXT[ext]
    if ext in TEXT_EXT or lower in TEXT_NAMES:
        return "text"
    return None


def decode_bytes(data: bytes) -> tuple[str, str] | None:
    """バイト列を文字にする。(文字, 文字コードの名前) を返す。文字のファイルでなければ None。"""
    if data.startswith(b"\xef\xbb\xbf"):
        try:
            return data[3:].decode("utf-8"), "utf-8-sig"
        except UnicodeDecodeError:
            return None
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        try:
            return data.decode("utf-16"), "utf-16"
        except UnicodeDecodeError:
            return None
    if b"\x00" in data[:8192]:
        return None
    for enc in ("utf-8", "cp932"):
        try:
            return data.decode(enc), enc
        except UnicodeDecodeError:
            continue
    return _decode_by_line(data)


def _decode_by_line(data: bytes) -> tuple[str, str] | None:
    """UTF-8 でも CP932 でもファイル全体を読めないとき(UTF-8 と Shift_JIS の行が混ざったもの、Latin-1 の著者名など)。
    行ごとに UTF-8 → CP932 を試し、どちらでも読めない行だけ、読めないバイトを置き換える。
    置き換えたバイトが多い(8 バイトを超え、全体の 1% も超える)ものは、文字のファイルではないとみなす。"""
    if b"\x00" in data:
        return None
    lines, bad = [], 0
    for raw in data.split(b"\n"):          # 0x0A は、UTF-8 でも Shift_JIS でも、文字の途中には現れない
        for enc in ("utf-8", "cp932"):
            try:
                lines.append(raw.decode(enc))
                break
            except UnicodeDecodeError:
                continue
        else:
            line = raw.decode("utf-8", errors="replace")
            bad += line.count("�")
            lines.append(line)
    if bad > 8 and bad * 100 > len(data):
        return None
    return "\n".join(lines), "mixed"


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _long_path(path: str) -> str:
    """Windows で、260 文字を超えるパスも開けるように、拡張の形(\\\\?\\)にする。ほかの OS ではそのまま。"""
    if os.name != "nt":
        return path
    p = os.path.abspath(path)
    if p.startswith("\\\\?\\"):
        return p
    if p.startswith("\\\\"):
        return "\\\\?\\UNC\\" + p[2:]
    return "\\\\?\\" + p


def _real(path: str | os.PathLike) -> str:
    """比べるための実際の場所(リンクをたどり、拡張の形を外し、Windows では大文字と小文字をそろえる)。"""
    p = os.path.realpath(path)
    if p.startswith("\\\\?\\UNC\\"):
        p = "\\\\" + p[8:]
    elif p.startswith("\\\\?\\"):
        p = p[4:]
    return os.path.normcase(p)


def _inside(path: str, root: str) -> bool:
    return path == root or path.startswith(root.rstrip(os.sep) + os.sep)


def _is_dir_link(entry: os.DirEntry) -> bool:
    """フォルダのリンクか。Windows のジャンクション(mklink /J)も含める(is_symlink() では分からない。
    os.path.isjunction は 3.12 から)。"""
    if entry.is_symlink():
        return True
    if os.name == "nt":
        try:
            st = entry.stat(follow_symlinks=False)
        except OSError:
            return False
        if getattr(st, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
            return getattr(st, "st_reparse_tag", 0) in (stat.IO_REPARSE_TAG_MOUNT_POINT, stat.IO_REPARSE_TAG_SYMLINK)
    return False


def iter_source_files(source: SourceConfig, index_cfg: IndexConfig, stats: IngestStats,
                      sources: list[SourceConfig] | None = None) -> Iterator[SourceFile]:
    """source のルートを歩き、索引に入れるファイルを、中身を読んだ形で返す(パスの順)。

    sources: 設定のすべての source。ほかの source のルートがこのルートの中にあれば、そのフォルダは歩かない
    (その source の側だけで取り込む。同じファイルを 2 回入れないため)。ファイルのリンクは取り込まない(ルートの
    中を指すものは symlink_inside、外を指すものは symlink_outside として数える)。フォルダのリンク・ジャンクション
    はたどらない(ルートの外や、上のフォルダに戻るものがあるため。ルートの中を指すものは、もとの場所で取り込まれる)。
    リンクそのものを root にした source があれば、そのフォルダはほかの source のルートとして扱う。
    """
    root = source.root
    if not root.is_dir():
        raise FileNotFoundError(f"source {source.id} のルートがありません: {root}")
    include = GlobSet(source.include)
    exclude = GlobSet((DEFAULT_EXCLUDED_GLOBS if source.default_excludes else []) + source.exclude)
    secrets = GlobSet(DEFAULT_SECRET_GLOBS if source.default_excludes else [])
    excluded_dirs = DEFAULT_EXCLUDED_DIRS if source.default_excludes else set()
    real_root = _real(root)
    real_roots = [real_root]
    nested: dict[str, str] = {}            # このルートの中にある、ほかの source のルート(相対パス → id)
    plain_root = os.path.normcase(os.path.abspath(root))
    for other in sources or []:
        if other.id == source.id or not other.root.is_dir():
            continue
        r = _real(other.root)
        real_roots.append(r)
        if r != real_root and _inside(r, real_root):
            nested[os.path.normcase(os.path.relpath(r, real_root))] = other.id
        # フォルダのリンク・ジャンクションそのものを root にした source(リンクの先がルートの外でも)。
        # こちらではたどらないフォルダを、その source が取り込む
        p = os.path.normcase(os.path.abspath(other.root))
        if p != plain_root and _inside(p, plain_root):
            nested.setdefault(os.path.relpath(p, plain_root), other.id)

    def indexable(rel: str, name: str) -> bool:
        """名前だけで見て、索引に入りうるファイルか(既定の名前で除いたフォルダの中を数えるため)。
        include が無ければ、先に拡張子を見る(正規表現より安いので。数は変わらない)。"""
        if not include and language_of(name) is None:
            return False
        if exclude.match(rel) or secrets.match(rel):
            return False
        return include.match(rel) if include else True

    # (フォルダ, ルートからの相対パス(/ で終わる), 既定の名前で除いたフォルダの中なら、数える先)。
    # 名前の順に、上から深さ優先で歩く(os.walk と同じ順)
    stack: list[tuple[str, str, list | None]] = [(_long_path(str(root)), "", None)]
    while stack:
        dirpath, rel_dir, counter = stack.pop()
        try:
            with os.scandir(dirpath) as it:
                entries = list(it)
        except OSError:
            if counter is None:
                stats.skip_dir("unreadable_dir", rel_dir.rstrip("/") or ".")
            continue
        dirs, files = [], []
        for e in entries:
            try:
                is_dir = e.is_dir()
            except OSError:
                is_dir = False
            (dirs if is_dir else files).append(e)
        dirs.sort(key=lambda e: e.name)
        files.sort(key=lambda e: e.name)

        sub = []
        for d in dirs:
            rel = rel_dir + d.name
            lower = d.name.lower()
            if exclude.match(rel + "/") or exclude.match(rel):
                continue
            if os.path.normcase(rel) in nested:
                if counter is None:
                    stats.nested_roots.append(f"{source.id}:{shown_path(rel)} → {nested[os.path.normcase(rel)]}")
                continue
            if _is_dir_link(d):
                if counter is None and lower not in excluded_dirs:
                    stats.skip_dir("link_dir", rel)
                continue
            if lower in UNCOUNTED_EXCLUDED_DIRS and lower in excluded_dirs:
                continue
            if counter is None and lower in excluded_dirs:
                record = [f"{source.id}:{shown_path(rel)}", 0]
                stats.excluded_dirs.append(record)
                sub.append((d.path, rel + "/", record))
                continue
            sub.append((d.path, rel + "/", counter))
        stack.extend(reversed(sub))

        for f in files:
            rel = rel_dir + f.name
            name = f.name
            if counter is not None:
                if indexable(rel, name):
                    counter[1] += 1
                continue
            stats.scanned += 1
            try:
                rel.encode("utf-8")
            except UnicodeEncodeError:          # 索引に書けない名前(UTF-8 でない Linux の名前、対になっていないサロゲート)
                stats.skip("bad_name", rel)
                continue
            if exclude.match(rel):
                stats.skip("excluded", rel)
                continue
            if secrets.match(rel):
                stats.skip("secret_name", rel)
                continue
            if include:
                if not include.match(rel):
                    stats.skip("not_included", rel)
                    continue
                lang = language_of(name) or "text"
            else:
                lang = language_of(name)
                if lang is None:
                    stats.skip("not_included", rel)
                    continue
            if f.is_symlink():
                # ルートの中を指すものは、指す先の場所で(その名前で除かれないなら)取り込まれる。リンクの名前で
                # 取り込むと、.env や .git の中のファイルが、秘密の名前・除くフォルダの決まりをすり抜けるので読まない
                inside = any(_inside(_real(f.path), r) for r in real_roots)
                stats.skip("symlink_inside" if inside else "symlink_outside", rel)
                continue
            full = Path(f.path)
            try:
                st = os.stat(f.path)
            except OSError:
                stats.skip("unreadable", rel)
                continue
            if st.st_size == 0:
                stats.skip("empty", rel)
                continue
            if st.st_size > index_cfg.max_file_bytes:
                stats.skip("too_large", rel)
                continue
            try:
                with open(f.path, "rb") as fh:
                    data = fh.read()
            except OSError:
                stats.skip("unreadable", rel)
                continue
            decoded = decode_bytes(data)
            if decoded is None:
                stats.skip("binary" if b"\x00" in data[:8192] else "undecodable", rel)
                continue
            text, enc = decoded
            text = normalize_newlines(text)
            if not text.strip():
                stats.skip("empty", rel)
                continue
            if index_cfg.skip_generated:
                if looks_generated(text, name):
                    stats.skip("generated", rel)
                    continue
                if index_cfg.max_line_chars and any(len(line) > index_cfg.max_line_chars for line in text.split("\n")):
                    stats.skip("long_lines", rel)
                    continue
            stats.included += 1
            yield SourceFile(source_id=source.id, path=rel, abs_path=full, size=st.st_size, mtime_ns=st.st_mtime_ns,
                             language=lang, encoding=enc, text=text)
