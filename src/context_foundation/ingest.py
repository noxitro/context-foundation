# ほかの名前(build・target・packages など)は、ソースの置き場にも使われるので、中の索引に入りうるファイルを
# 数えて status に出す
UNCOUNTED_EXCLUDED_DIRS = {
    ".git", ".svn", ".hg", ".p4", ".cf", ".index", ".cache", ".venv", "venv", "__pycache__", "node_modules",
    ".gradle", ".vs", ".vscode", ".idea", "intermediate", "deriveddatacache",
}

# 生成物の印。ファイルの頭(先頭 2,000 文字)の、コメントの行だけを見る。文書(Markdown・.txt など)には当てない
# (「ダンジョン自動生成の仕様」のような題や、文の途中の "generated by" で、手書きのものを落とさないため)。
# コメントの行の頭の記号。' は VB の拡張子、<!-- はマークアップの拡張子のときだけコメントとみなす
# (ほかの言語では、文字列の中の行のことがあるため)
_COMMENT_LINE = re.compile(
    r"""^\s*(?P<mark>//+|/\*+|\*+|--|;+|<!--|<\#|"{3}|'{3}|'|::|rem\b
            |\#+(?!\s*(?:include|import|if|ifdef|ifndef|elif|else|endif|define|undef|pragma|region|endregion
                        |line|error|warning|using|nullable)\b))
        \s*(?P<body>.*)$""", re.IGNORECASE | re.VERBOSE)
# `#` がコメントの始まりの言語(Python・シェル・CMake・YAML など)。ここでは、上で外したプリプロセッサの語
# (include・if・warning・using など)で始まる `#` の行もコメントの行とみなす(「# WARNING: This file is
# auto-generated」を見落とさないため)。ほかの言語(C 系・シェーダー・Rust の #[...] など)では、コードの行のまま
_HASH_LINE = re.compile(r"^\s*(?P<mark>\#+)\s*(?P<body>.*)$")
_HASH_COMMENT_EXT = {".py", ".sh", ".cmake", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".rb", ".ps1"}
_HASH_COMMENT_NAMES = {"makefile", "dockerfile"}
_VB_EXT ={".vb", ".bas", ".vbs", ".cls", ".frm"}
_MARKUP_EXT = {".xml", ".html", ".htm", ".xhtml", ".xaml", ".natvis", ".svg", ".xsd", ".xsl", ".xslt", ".config",
               ".csproj", ".vcxproj", ".props", ".targets", ".resx", ".uxml", ".vue"}
# ファイルの頭で開いたブロックコメント(と docstring)の閉じ。中の行は、記号が無くてもコメントの行として見る
_BLOCK_CLOSE = {"/*": "*/", "<!--": "-->", '"""': '"""', "'''": "'''"}
# 印の書き出しの前に許すもの: 飾りの記号と、短い前置き(NOTE:・WARNING:・注意: など)
_LEAD_IN = r"[\W_]*(?:(?:note|warning|caution|attention|important|notice|注意|警告|注)\s*[:：!！\-][\W_]*)?"
# 先頭 2,000 文字の、どのコメントの行でも、書き出しにあれば印とみなすもの(0.3.1 が見ていたバナーの形)
_GENERATED_STRONG = re.compile(
    _LEAD_IN + r"(?:this (?:file|code) (?:was|is|has been) (?:auto(?:matically)?[- ]?)?generated\b"
    r"|(?:the )?file (?:(?:was|is|has been) )?(?:auto(?:matically)?[- ]?)?generated\b"
    r"|(?:code |auto(?:matically)?[- ]?)?generated by\b(?!:)|automatically generated\b|autogenerated\b"
    r"|(?:この|本|当)(?:ファイル|ソース|コード|ヘッダ)は.{0,24}自動生成|これは自動生成|自動生成(?:ファイル|コード))",
    re.IGNORECASE)
# ファイルの頭のコメントのかたまり(最初のコードの行より前)にあるときだけ印とみなすもの
# (説明のコメントにもよく出る書き方なので、コードの後ろでは見ない)
_GENERATED_WEAK = re.compile(
    _LEAD_IN + r"(?:auto(?:matically)?[- ]?generated\b|generated (?:from|with|using)\b|code generated\b"
    r"|(?:an? )?(?:[^\W_][\w-]* )?(?:loader|scanner|parser|lexer|contents|bindings?|wrappers?|stubs?|tables?) generated by\b"
    r"|this (?:header|class|source|module)(?: file)? (?:was|is|has been) (?:auto(?:matically)?[- ]?)?generated\b"
    r"|自動生成(?:され|した))",
    re.IGNORECASE)
# コメントの行のどこにあっても印とみなすもの(DO NOT EDIT は大文字のときだけ。小文字は、同じ行に generated があるとき)
_GENERATED_ANYWHERE = re.compile(r"@generated\b|<auto-?generated\b|(?-i:DO NOT EDIT)", re.IGNORECASE)
_DO_NOT_EDIT = re.compile(r"\bdo not edit\b", re.IGNORECASE)
DOCUMENT_EXT = {".md", ".markdown", ".mdx", ".txt", ".rst", ".adoc"}


def _generated_mark(body: str, head: bool) -> bool:
    """コメントの本文に生成物の印があるか。head: ファイルの頭のコメントのかたまりの中か。"""
    if _GENERATED_ANYWHERE.search(body) or _GENERATED_STRONG.match(body):
        return True
    if _DO_NOT_EDIT.search(body) and "generated" in body.lower():
        return True
    return head and _GENERATED_WEAK.match(body) is not None


def looks_generated(text: str, name: str) -> bool:
    """ファイルの頭のコメントに、生成物の印があるか。文書(Markdown・.txt など)は見ない。"""
    ext = os.path.splitext(name.lower())[1]
    if ext in DOCUMENT_EXT:
        return False
    hash_comments = ext in _HASH_COMMENT_EXT or os.path.basename(name.lower()) in _HASH_COMMENT_NAMES
    head = True            # まだ最初のコードの行より前か
    close = None          # ファイルの頭で開いたままのブロックコメントの閉じ
    for line in text[:2000].split("\n"):
        if close is not None:
            body, sep, _ = line.partition(close)
            if sep:
                close = None
            if _generated_mark(body.strip().lstrip("*").strip(), True):
                return True
            continue
        if not line.strip():
            continue
        m = _COMMENT_LINE.match(line)
        if m is None and hash_comments:
            m = _HASH_LINE.match(line)
        mark = m["mark"] if m else ""
        if (mark == "'" and ext not in _VB_EXT) or (mark == "<!--" and ext not in _MARKUP_EXT):
            m = None
        if m is None:
            if not (head and line.lstrip().startswith("<?xml")):
                head = False
            continue
        body = m["body"]
        if head:
            end = _BLOCK_CLOSE.get("/*" if mark.startswith("/*") else mark)
            if end is not None and end not in body:
                close = end
        if _generated_mark(body, head):
            return True
    return False


def glob_to_regex(pattern: str) -> re.Pattern:
    """glob を正規表現にする。`**` はフォルダをまたぎ、`*` と `?` は `/` をまたがない。

    `/` を含まない glob は、どの深さの名前にも一致する(`.gitignore` と同じ読み方)。
    大文字と小文字は区別しない(Windows のパスを想定)。
    """
    pat = pattern.replace("\\", "/").strip().rstrip("/")
    anchored = pat.startswith("/")
    pat = pat.lstrip("/")
    if "/" not in pat and not anchored:
        pat = "**/" + pat
    out, i, n = [], 0, len(pat)
    while i < n:
        c = pat[i]
        if c == "*":
            if pat[i:i + 3] == "**/":
                out.append("(?:.*/)?")
                i += 3
                continue
            if pat[i:i + 2] == "**":
                out.append(".*")
                i += 2
                continue
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        elif c == "[":
            j = pat.find("]", i + 1)
            if j < 0:
                out.append(re.escape(c))
            else:
                body = pat[i + 1:j]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body.replace("\\", "\\\\") + "]")
                i = j
        else:
            out.append(re.escape(c))
        i += 1
    # 一致した名前がフォルダなら、その下もすべて一致とみなす(`build/` のように / で終わる glob も同じ読み方)
    return re.compile("^" + "".join(out) + "(?:/.*)?$", re.IGNORECASE)


class GlobSet:
    def __init__(self, patterns: list[str]):
        self.patterns = list(patterns)
        self._res = [glob_to_regex(p) for p in patterns]

    def match(self, rel_posix: str) -> bool:
        return any(r.match(rel_posix) for r in self._res)

    def __bool__(self) -> bool:
        return bool(self._res)


@dataclass
class SourceFile:
    source_id: str
    path: str            # source のルートからの相対パス(区切りは /)
    abs_path: Path
    size: int
    mtime_ns: int
    language: str        # c / cpp / csharp / markdown / text
