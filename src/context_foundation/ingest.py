"""取り込み: source のルートを歩いて、索引に入れるファイルを選び、文字に直す。

- git には頼らない(`.gitignore` も読まない)。除外は、既定のフォルダ名と設定の glob で決める
- バイナリ・生成物・大きすぎるファイルを除き、除いた数を理由ごとに数える
- 文字コードは BOM → UTF-8 → CP932(Shift_JIS)の順に試す
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator

from .config import IndexConfig, SourceConfig

# 拡張子 → 言語(分割の方法を決める)
LANG_BY_EXT = {
    **{e: "c" for e in (".c",)},
    **{e: "cpp" for e in (".h", ".hh", ".hpp", ".hxx", ".h++", ".cc", ".cpp", ".cxx", ".c++", ".inl", ".ipp", ".tpp",
                          ".ixx", ".cppm")},
    ".cs": "csharp",
    **{e: "markdown" for e in (".md", ".markdown", ".mdx")},
}
# 行で分ける、そのほかの文字のファイル
TEXT_EXT = {
    ".txt", ".rst", ".adoc",
    ".py", ".lua", ".js", ".jsx", ".ts", ".tsx", ".java", ".kt", ".swift", ".rs", ".go", ".rb", ".php", ".m", ".mm",
    ".sh", ".ps1", ".bat", ".cmd", ".cmake", ".gradle",
    ".hlsl", ".hlsli", ".glsl", ".vert", ".frag", ".comp", ".shader", ".cginc", ".fx", ".fxh", ".azsl", ".azsli",
    ".usf", ".ush",
    ".yaml", ".yml", ".toml", ".ini", ".cfg", ".proto", ".fbs", ".sql", ".natvis",
}
TEXT_NAMES = {"cmakelists.txt", "makefile", "dockerfile"}

# どこにあっても入らないフォルダ(版管理・ビルドの出力・依存物・この道具自身の置き場)
DEFAULT_EXCLUDED_DIRS = {
    ".git", ".svn", ".hg", ".p4", ".vs", ".vscode", ".idea", ".cf", ".index", ".cache", ".venv", "venv",
    "__pycache__", "node_modules", "build", "out", "bin", "obj", "dist", "target", "intermediate", "binaries",
    "deriveddatacache", "saved", ".gradle", "packages",
}
# 生成物によくある名前
DEFAULT_EXCLUDED_GLOBS = [
    "*.generated.*", "*.gen.*", "*.g.cs", "*.g.i.cs", "*.designer.cs", "*.min.js", "*.min.css",
    "*.pb.h", "*.pb.cc", "*_generated.h", "moc_*.cpp", "ui_*.h", "package-lock.json",
]
# 先頭の近くにこの文があれば、生成物とみなす
GENERATED_MARKERS = re.compile(
    r"<auto-?generated|@generated|do not edit|generated by |this file (?:was|is) (?:auto[- ]?)?generated|"
    r"automatically generated|autogenerated|自動生成",
    re.IGNORECASE)


def glob_to_regex(pattern: str) -> re.Pattern:
    """glob を正規表現にする。`**` はフォルダをまたぎ、`*` と `?` は `/` をまたがない。

    `/` を含まない glob は、どの深さの名前にも一致する(`.gitignore` と同じ読み方)。
    大文字と小文字は区別しない(Windows のパスを想定)。
    """
    pat = pattern.replace("\\", "/").strip().rstrip("/")
    anchored = pat.startswith("/")
    pat = pat.lstrip("/")
    if "/" not in pat and not anchored:
        pat = "**/" + pat
    out, i, n = [], 0, len(pat)
    while i < n:
        c = pat[i]
        if c == "*":
            if pat[i:i + 3] == "**/":
                out.append("(?:.*/)?")
                i += 3
                continue
            if pat[i:i + 2] == "**":
                out.append(".*")
                i += 2
                continue
            out.append("[^/]*")
        elif c == "?":
            out.append("[^/]")
        elif c == "[":
            j = pat.find("]", i + 1)
            if j < 0:
                out.append(re.escape(c))
            else:
                body = pat[i + 1:j]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body.replace("\\", "\\\\") + "]")
                i = j
        else:
            out.append(re.escape(c))
        i += 1
    # 一致した名前がフォルダなら、その下もすべて一致とみなす(`build/` のように / で終わる glob も同じ読み方)
    return re.compile("^" + "".join(out) + "(?:/.*)?$", re.IGNORECASE)


class GlobSet:
    def __init__(self, patterns: list[str]):
        self.patterns = list(patterns)
        self._res = [glob_to_regex(p) for p in patterns]

    def match(self, rel_posix: str) -> bool:
        return any(r.match(rel_posix) for r in self._res)

    def __bool__(self) -> bool:
        return bool(self._res)


@dataclass
class SourceFile:
    source_id: str
    path: str            # source のルートからの相対パス(区切りは /)
    abs_path: Path
    size: int
    mtime_ns: int
    language: str        # c / cpp / csharp / markdown / text
    encoding: str = ""
    text: str = ""


@dataclass
class IngestStats:
    scanned: int = 0                 # 見たファイルの数(除外したフォルダの中は数えない)
    included: int = 0
    skipped: dict[str, int] = field(default_factory=dict)
    examples: dict[str, list[str]] = field(default_factory=dict)   # 理由ごとに、除いたファイルの例を少し

    def skip(self, reason: str, rel: str) -> None:
        self.skipped[reason] = self.skipped.get(reason, 0) + 1
        ex = self.examples.setdefault(reason, [])
        if len(ex) < 5:
            ex.append(rel)


def language_of(name: str) -> str | None:
    lower = name.lower()
    ext = os.path.splitext(lower)[1]
    if ext in LANG_BY_EXT:
        return LANG_BY_EXT[ext]
    if ext in TEXT_EXT or lower in TEXT_NAMES:
        return "text"
    return None


def decode_bytes(data: bytes) -> tuple[str, str] | None:
    """バイト列を文字にする。(文字, 文字コードの名前) を返す。文字のファイルでなければ None。"""
    if data.startswith(b"\xef\xbb\xbf"):
        try:
            return data[3:].decode("utf-8"), "utf-8-sig"
        except UnicodeDecodeError:
            return None
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        try:
            return data.decode("utf-16"), "utf-16"
        except UnicodeDecodeError:
            return None
    if b"\x00" in data[:8192]:
        return None
    for enc in ("utf-8", "cp932"):
        try:
            return data.decode(enc), enc
        except UnicodeDecodeError:
            continue
    return None


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def iter_source_files(source: SourceConfig, index_cfg: IndexConfig, stats: IngestStats) -> Iterator[SourceFile]:
    """source のルートを歩き、索引に入れるファイルを、中身を読んだ形で返す(パスの順)。"""
    root = source.root
    if not root.is_dir():
        raise FileNotFoundError(f"source {source.id} のルートがありません: {root}")
    include = GlobSet(source.include)
    exclude = GlobSet((DEFAULT_EXCLUDED_GLOBS if source.default_excludes else []) + source.exclude)
    excluded_dirs = DEFAULT_EXCLUDED_DIRS if source.default_excludes else set()

    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        rel_dir = os.path.relpath(dirpath, root).replace("\\", "/")
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        keep = []
        for d in sorted(dirnames):
            rel = rel_dir + d
            if d.lower() in excluded_dirs or exclude.match(rel + "/") or exclude.match(rel):
                continue
            keep.append(d)
        dirnames[:] = keep
        for name in sorted(filenames):
            rel = rel_dir + name
            stats.scanned += 1
            if exclude.match(rel):
                stats.skip("excluded", rel)
                continue
            if include:
                if not include.match(rel):
                    stats.skip("not_included", rel)
                    continue
                lang = language_of(name) or "text"
            else:
                lang = language_of(name)
                if lang is None:
                    stats.skip("not_included", rel)
                    continue
            full = Path(dirpath) / name
            try:
                st = full.stat()
            except OSError:
                stats.skip("unreadable", rel)
                continue
            if st.st_size == 0:
                stats.skip("empty", rel)
                continue
            if st.st_size > index_cfg.max_file_bytes:
                stats.skip("too_large", rel)
                continue
            try:
                data = full.read_bytes()
            except OSError:
                stats.skip("unreadable", rel)
                continue
            decoded = decode_bytes(data)
            if decoded is None:
                stats.skip("binary", rel)
                continue
            text, enc = decoded
            text = normalize_newlines(text)
            if not text.strip():
                stats.skip("empty", rel)
                continue
            if index_cfg.skip_generated:
                if GENERATED_MARKERS.search(text[:2000]):
                    stats.skip("generated", rel)
                    continue
                if index_cfg.max_line_chars and any(len(line) > index_cfg.max_line_chars for line in text.split("\n")):
                    stats.skip("long_lines", rel)
                    continue
            stats.included += 1
            yield SourceFile(source_id=source.id, path=rel, abs_path=full, size=st.st_size, mtime_ns=st.st_mtime_ns,
                             language=lang, encoding=enc, text=text)
