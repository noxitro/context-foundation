"""取り込み: source のルートを歩いて、索引に入れるファイルを選び、文字に直す。

- git には頼らない(`.gitignore` も読まない)。除外は、既定のフォルダ名と設定の glob で決める
- バイナリ・生成物・大きすぎるファイル・秘密を持ちやすい名前のファイルを除き、除いた数を理由ごとに数える。
  既定の名前で除いたフォルダは、中にある索引に入りうるファイルを数えて残す(status に出す)
- フォルダのリンク・ジャンクションはたどらない(それを root にした source があれば、その source で取り込む)。
  ファイルのリンクも読まない(ルートの中を指すものは、指す先の場所で取り込まれる)
- 文字コードは BOM → UTF-8 → CP932(Shift_JIS)の順に試す。どれでも読めなければ、行ごとに試す
"""
from __future__ import annotations

import os
import re
import stat
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator

