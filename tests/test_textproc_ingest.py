"""語の分け方(keyword 用)と、取り込み(除外・文字コード)。"""
from __future__ import annotations

from context_foundation.config import IndexConfig, SourceConfig
from context_foundation.ingest import GlobSet, IngestStats, decode_bytes, iter_source_files
from context_foundation.textproc import fts_query, query_tokens, tokenize


def test_identifiers_are_indexed_whole_and_in_parts():
    toks = tokenize("ResultCode BufferPool::Init(m_bufferCount2D, HTTPServer, snake_case_name)")
    for want in ("bufferpool", "buffer", "pool", "init", "resultcode", "result", "http", "server",
                 "snake_case_name", "case", "name", "count"):
        assert want in toks
    assert "snak" in toks        # 語末の e は落とす(索引と質問で同じ規則)


def test_english_endings_are_folded():
    assert tokenize("initialize initializes initialized initializing") == ["initializ"] * 4
    assert tokenize("buffers pools") == ["buffer", "pool"]


def test_japanese_becomes_bigrams():
    assert tokenize("描画処理") == ["描画", "画処", "処理"]
    q = query_tokens("GPU のバッファを使い回す仕組みはどこですか")
    assert "gpu" in q and "バッ" in q and "仕組" in q
    assert "です" not in q and "すか" not in q          # ひらがなだけの組は、質問からは落とす


def test_query_drops_stopwords_and_duplicates():
    assert query_tokens("Where is the buffer pool, and where are the buffers?") == ["buffer", "pool"]
    assert fts_query(["buffer", "pool"]) == '"buffer" OR "pool"'


def test_glob_matching():
    g = GlobSet(["**/ThirdParty/**", "*.generated.cs", "build/", "/top_only.txt", "docs/*.md"])
    assert g.match("Engine/ThirdParty/zlib/zlib.h")
    assert g.match("src/Foo.generated.cs") and g.match("Foo.generated.cs")
    assert g.match("a/build/x.cpp") and g.match("build")
    assert not g.match("a/builder/x.cpp")
    assert g.match("top_only.txt") and not g.match("sub/top_only.txt")
    assert g.match("docs/a.md") and not g.match("docs/sub/a.md")
    assert g.match("ENGINE/thirdparty/a.h")              # 大文字と小文字は区別しない


def test_ingest_skips_binary_generated_large_and_excluded(tmp_path):
    root = tmp_path / "src"
    (root / "code").mkdir(parents=True)
    (root / "build").mkdir()
    (root / ".git").mkdir()
    (root / "code" / "a.cpp").write_text("int a() { return 1; }\n", encoding="utf-8")
    (root / "code" / "sjis.cpp").write_bytes("// 日本語のコメント\nint b();\n".encode("cp932"))
    (root / "code" / "bom.cs").write_bytes(b"\xef\xbb\xbfclass C {}\n")
    (root / "code" / "bin.cpp").write_bytes(b"\x00\x01\x02binary")
    (root / "code" / "gen.cpp").write_text("// <auto-generated>\nint g;\n", encoding="utf-8")
    (root / "code" / "big.cpp").write_text("int x;\n" * 4000, encoding="utf-8")
    (root / "code" / "min.js").write_text("var a=" + "1+" * 4000 + "1;\n", encoding="utf-8")
    (root / "code" / "image.png").write_bytes(b"\x89PNG")
    (root / "build" / "out.cpp").write_text("int o;\n", encoding="utf-8")
    (root / ".git" / "config.txt").write_text("x\n", encoding="utf-8")
    stats = IngestStats()
    files = list(iter_source_files(SourceConfig(id="s", root=root), IndexConfig(max_file_bytes=20_000), stats))
    got = {f.path: f for f in files}
    assert set(got) == {"code/a.cpp", "code/sjis.cpp", "code/bom.cs"}
    assert got["code/sjis.cpp"].encoding == "cp932" and "日本語のコメント" in got["code/sjis.cpp"].text
    assert got["code/bom.cs"].text.startswith("class C")
    assert got["code/a.cpp"].language == "cpp" and got["code/bom.cs"].language == "csharp"
    assert stats.skipped == {"binary": 1, "generated": 1, "too_large": 1, "long_lines": 1, "not_included": 1}


def test_ingest_include_and_exclude_globs(tmp_path):
    root = tmp_path / "src"
    (root / "keep").mkdir(parents=True)
    (root / "drop").mkdir()
    (root / "keep" / "a.cpp").write_text("int a;\n", encoding="utf-8")
    (root / "keep" / "notes.xyz").write_text("plain notes\n", encoding="utf-8")
    (root / "drop" / "b.cpp").write_text("int b;\n", encoding="utf-8")
    src = SourceConfig(id="s", root=root, include=["**/*.cpp", "**/*.xyz"], exclude=["drop/"])
    files = {f.path: f.language for f in iter_source_files(src, IndexConfig(), IngestStats())}
    assert files == {"keep/a.cpp": "cpp", "keep/notes.xyz": "text"}


def test_decode_rejects_binary():
    assert decode_bytes(b"abc\x00def") is None
    assert decode_bytes("こんにちは".encode("utf-16"))[1] == "utf-16"
